    fun byCode(code: String): CurrencyEntry =
        ALL.firstOrNull { it.code == code } ?: POPULAR.firstOrNull { it.code == code }
            ?: CurrencyEntry("PLN", "z\u0142", "Poland", "Polish zloty")

    fun symbol(code: String): String = byCode(code).symbol

    fun search(query: String): List<CurrencyEntry> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return ALL
        return ALL.filter { entry ->
            entry.code.lowercase().startsWith(q) ||
                entry.country.lowercase().contains(q) ||
                entry.name.lowercase().contains(q) ||
                entry.symbol.lowercase() == q
        }
    }
